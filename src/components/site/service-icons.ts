export type ServiceIconName = (typeof SERVICE_ICONS)[number]["name"];

export const SERVICE_ICON_MAP = Object.fromEntries(
  SERVICE_ICONS.map((i) => [i.name, i.Icon]),
) as Readonly<Record<ServiceIconName, LucideIcon>>;

/** DB `services.icon` is free text; anything not in the registry renders as "sparkles". */
export function toServiceIcon(icon: string | null): ServiceIconName {
  return icon && Object.hasOwn(SERVICE_ICON_MAP, icon) ? (icon as ServiceIconName) : "sparkles";
}
